"""Embed the hardware tester as deterministic gzip assets for the C6 gateway."""
from pathlib import Path
import gzip
import hashlib
def generate(project):
    source=project/"tools"/"hardware-test"
    html=(source/"index.html").read_text(encoding="utf-8")
    html=html.replace('<html lang="en">','<html lang="en" data-hosted="c6">')
    html=html.replace('href="/styles.css"','href="/hardware-test/styles.css"').replace('src="/app.js"','src="/hardware-test/app.js"')
    assets={"HTML":html,"JS":(source/"app.js").read_text(encoding="utf-8"),"CSS":(source/"styles.css").read_text(encoding="utf-8")}
    lines=["#pragma once","// Generated by tools/hardware-test/embed_assets.py; edit the source assets.","namespace hardware_test {"]
    digest=hashlib.sha256()
    for name,content in assets.items():
        data=content.encode("utf-8");digest.update(data)
        packed=gzip.compress(data,compresslevel=9,mtime=0)
        lines.append("static const unsigned char "+name+"[]={")
        lines.extend(",".join(str(n) for n in packed[i:i+24])+"," for i in range(0,len(packed),24))
        lines.append("};")
    lines.append('static constexpr char SOURCE_SHA256[]="'+digest.hexdigest()+'";')
    lines.append("}")
    output=project/"gateway"/"src"/"HardwareTestAssets.h"
    text="\n".join(lines)+"\n"
    if not output.exists() or output.read_text(encoding="utf-8")!=text:output.write_text(text,encoding="utf-8",newline="\n")
    print("Embedded hardware tester: "+digest.hexdigest()[:12])
try:
    Import("env")
except NameError:
    env=None
generate(Path(env.subst("$PROJECT_DIR")).parent if env is not None else Path(__file__).resolve().parents[2])
